-- Migration 015: Convert table primary keys from UUID to auto-incrementing bigint identity
-- Scope: All 14 public entity tables:
--   1. expenses
--   2. expense_comments (including foreign key reference expense_id -> expenses.id)
--   3. subscriptions
--   4. monthly_snapshots
--   5. month_comments
--   6. budget_memberships
--   7. user_settings
--   8. accounts
--   9. savings_goals
--  10. investments
--  11. category_budgets
--  12. notifications
--  13. user_income_sources
--  14. receipt_queue
--
-- Note: auth.users(id) and user_id columns remain UUID as required by Supabase Auth (GoTrue).

-- ============================================================================
-- 1. Table: public.expenses & public.expense_comments (Cascaded Foreign Key)
-- ============================================================================
do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'expenses'
      and column_name = 'id'
      and data_type = 'uuid'
  ) then
    -- 1. Add new identity column to expenses
    alter table public.expenses add column new_id bigint generated by default as identity;

    -- 2. Handle expense_comments referencing expenses.id
    if exists (
      select 1
      from information_schema.tables
      where table_schema = 'public' and table_name = 'expense_comments'
    ) then
      alter table public.expense_comments add column if not exists new_expense_id bigint;

      -- Map existing comments to the new integer expense id
      update public.expense_comments c
      set new_expense_id = e.new_id
      from public.expenses e
      where c.expense_id = e.id;

      -- Drop policies on expense_comments that reference expenses.id or expense_comments.expense_id
      drop policy if exists "budget members can read expense comments" on public.expense_comments;
      drop policy if exists "reviewer can insert expense comments" on public.expense_comments;
      drop policy if exists "owner can insert expense comments" on public.expense_comments;
      drop policy if exists "owner can delete expense comments" on public.expense_comments;
      drop policy if exists "users can manage comments for own expenses" on public.expense_comments;
      drop policy if exists "owner can manage expense comments for own expenses" on public.expense_comments;
      drop policy if exists "reviewer can add expense comments" on public.expense_comments;
      drop policy if exists "reviewer can read expense comments" on public.expense_comments;

      -- Drop foreign key constraint
      alter table public.expense_comments drop constraint if exists expense_comments_expense_id_fkey cascade;
    end if;

    -- 3. Swap primary key on public.expenses
    alter table public.expenses drop constraint if exists expenses_pkey cascade;
    alter table public.expenses drop column id cascade;
    alter table public.expenses rename column new_id to id;
    alter table public.expenses add constraint expenses_pkey primary key (id);

    -- 4. Swap expense_id on public.expense_comments and recreate foreign key + RLS
    if exists (
      select 1
      from information_schema.tables
      where table_schema = 'public' and table_name = 'expense_comments'
    ) then
      alter table public.expense_comments drop column if exists expense_id cascade;
      alter table public.expense_comments rename column new_expense_id to expense_id;
      alter table public.expense_comments alter column expense_id set not null;
      alter table public.expense_comments add constraint expense_comments_expense_id_fkey
        foreign key (expense_id) references public.expenses(id) on delete cascade;

      -- Recreate index on expense_comments (expense_id, created_at desc)
      drop index if exists public.expense_comments_expense_id_created_at_idx;
      create index if not exists expense_comments_expense_id_created_at_idx
        on public.expense_comments (expense_id, created_at desc);

      -- Recreate RLS policies on public.expense_comments
      create policy "budget members can read expense comments"
      on public.expense_comments
      for select
      using (
        exists (
          select 1
          from public.expenses e
          where e.id = public.expense_comments.expense_id
            and public.can_access_owner_budget(e.user_id)
        )
      );

      create policy "owner can insert expense comments"
      on public.expense_comments
      for insert
      with check (
        author_role = 'owner'
        and public.is_budget_owner_account()
        and exists (
          select 1
          from public.expenses e
          where e.id = public.expense_comments.expense_id
            and e.user_id = auth.uid()
        )
      );

      create policy "reviewer can insert expense comments"
      on public.expense_comments
      for insert
      with check (
        author_role = 'reviewer'
        and exists (
          select 1
          from public.expenses e
          where e.id = public.expense_comments.expense_id
            and public.is_budget_reviewer(e.user_id)
        )
      );

      create policy "owner can delete expense comments"
      on public.expense_comments
      for delete
      using (
        public.is_budget_owner_account()
        and exists (
          select 1
          from public.expenses e
          where e.id = public.expense_comments.expense_id
            and e.user_id = auth.uid()
        )
      );
    end if;
  end if;
end $$;

